r"""Generate crates/nrmlz/src/pytables.rs: the character classes of the pinned Python (re \w, \s, \d,
str.isdigit, str.isupper), so the Rust port matches Python's Unicode database exactly.

Run with the reference interpreter: python -I tools/scripts/gen_unicode_tables.py > crates/nrmlz/src/pytables.rs
"""
import re
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, rs):
    print(f"/// {doc}")
    print(f"pub static {name}: &[(u32, u32)] = &[")
    for i in range(0, len(rs), 6):
        print("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i:i + 6]))
    print("];")


w, s, d = re.compile(r"\w"), re.compile(r"\s"), re.compile(r"\d")
print("// Generated by tools/scripts/gen_unicode_tables.py. Do not edit.")
print(f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.")
print()
emit("WORD", "Python re `\\w` (str patterns).", ranges(lambda c: w.match(c) is not None))
emit("SPACE", "Python re `\\s` and str.isspace().", ranges(lambda c: s.match(c) is not None))
emit("DECIMAL", "Python re `\\d` and str.isdecimal(); every range starts at digit zero.",
     ranges(lambda c: d.match(c) is not None))
emit("DIGIT", "str.isdigit() for one character.", ranges(lambda c: c.isdigit()))
emit("UPPER", "str.isupper() for one character.", ranges(lambda c: c.isupper()))
